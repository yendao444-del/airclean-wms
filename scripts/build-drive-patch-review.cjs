const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const root = path.resolve(__dirname, "..");
const stage = path.join(root, "tmp", "drive-patch-stage");
fs.rmSync(stage, { recursive: true, force: true });
const app = path.join(stage, "resources", "app");
for (const dir of ["dist", "electron", "node_modules", "python"]) fs.mkdirSync(path.join(app, dir), { recursive: true });
const copy = (from, to) => fs.cpSync(path.join(root, from), path.join(app, to), { recursive: true, force: true });
copy("dist", "dist"); copy("electron", "electron"); copy("package.json", "package.json");
for (const name of ["@supabase", "@zxing", "cloudflared", "iceberg-js", "tslib", "ws"]) copy(path.join("node_modules", name), path.join("node_modules", name));
for (const name of ["attendance_service.py", "requirements.txt"]) copy(path.join("python", name), path.join("python", name));
for (const name of ["config.js", "supabase-storage.json", "gdrive-token.json", "gdrive-token.bin", "gdrive-credentials.json", "google-oauth-config.json", "r2-daily-evidence-bootstrap.json"]) fs.rmSync(path.join(app, "electron", name), { force: true });
execFileSync(process.execPath, [path.join(root, "scripts", "prepare-drive-backend-stage.cjs"), path.join(app, "electron")], { stdio: "inherit" });
const zip = path.join(root, "tmp", "DBYPOS-drive-patch-v1.0.468.zip");
fs.rmSync(zip, { force: true });
execFileSync("powershell.exe", ["-NoProfile", "-Command", `Compress-Archive -Path '${path.join(stage, "*")}' -DestinationPath '${zip}' -Force`], { stdio: "inherit" });
const hash = require("crypto").createHash("sha256").update(fs.readFileSync(zip)).digest("hex");
fs.writeFileSync(`${zip}.sha256`, `${hash}  ${path.basename(zip)}\n`);
console.log(zip);
